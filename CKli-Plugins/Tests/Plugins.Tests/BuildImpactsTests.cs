using CK.Core;
using CKli;
using NUnit.Framework;
using Shouldly;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using static CK.Testing.MonitorTestHelper;

namespace Plugins.Tests;

/// <summary>
/// The impacts of a build are the files it creates, modifies or deletes in the working folder. They fail the build
/// unless "--build-impacts commit" (amended to the built commit, that is built again) or "--build-impacts discard"
/// (erased by the reset that follows the build). "publish" has no option: impacts always fail it.
/// </summary>
public class BuildImpactsTests
{
    const string _generated = "Generated.txt";

    // Creates a file, modifies a tracked one and deletes another tracked one. The same thing each time: the build
    // of the amended commit has no impact.
    static void ImpactingBuild( NormalizedPath workingFolder )
    {
        File.WriteAllText( workingFolder.AppendPart( _generated ), "Generated by the build." );
        File.WriteAllText( workingFolder.AppendPart( "Modified.txt" ), "Modified by the build." );
        File.Delete( workingFolder.AppendPart( "Deleted.txt" ) );
    }

    static async Task<FakeBuildRepo> CreateImpactedRepoAsync( FakeBuildWorld world )
    {
        var r = await world.CreateRepoAsync( "X-Impacted", "v1.0.0" ).ConfigureAwait( false );
        TestHelper.TouchAndCommit( r.WorkingFolderPath, branchName: null, fileName: "Modified.txt" );
        TestHelper.TouchAndCommit( r.WorkingFolderPath, branchName: null, fileName: "Deleted.txt" );
        r.OnBuild = ImpactingBuild;
        return r;
    }

    [Test]
    public async Task impacts_fail_the_build_by_default_Async()
    {
        using var testEnv = await TestHelper.CKliCreateFakeBuildTestEnvAsync().ConfigureAwait( false );
        var stack = await testEnv.CreateStackAsync( pluginConfigurationEditor: Helper.ConfigureFakeFeeds ).ConfigureAwait( false );
        var r = await CreateImpactedRepoAsync( stack.DefaultWorld ).ConfigureAwait( false );

        int tagsBefore = TagCount( r );
        using( TestHelper.Monitor.CollectTexts( out var logs ) )
        {
            (await CKliCommands.ExecAsync( TestHelper.Monitor, r.Root, "build" )).ShouldBeFalse();
            var error = logs.Single( t => t.Contains( "files that a build creates, modifies or deletes must be committed or ignored" ) );
            error.ShouldContain( $"created: {_generated}" );
            error.ShouldContain( "modified: Modified.txt" );
            error.ShouldContain( "deleted: Deleted.txt" );
        }
        TagCount( r ).ShouldBe( tagsBefore, "No version has been tagged." );
        File.Exists( r.WorkingFolderPath.AppendPart( _generated ) ).ShouldBeFalse( "The working folder has been reset." );
        File.Exists( r.WorkingFolderPath.AppendPart( "Deleted.txt" ) ).ShouldBeTrue( "The working folder has been reset." );
    }

    [Test]
    public async Task impacts_can_be_discarded_Async()
    {
        using var testEnv = await TestHelper.CKliCreateFakeBuildTestEnvAsync().ConfigureAwait( false );
        var stack = await testEnv.CreateStackAsync( pluginConfigurationEditor: Helper.ConfigureFakeFeeds ).ConfigureAwait( false );
        var r = await CreateImpactedRepoAsync( stack.DefaultWorld ).ConfigureAwait( false );

        int tagsBefore = TagCount( r );
        (await CKliCommands.ExecAsync( TestHelper.Monitor, r.Root, "build", "--build-impacts", "discard" )).ShouldBeTrue();
        TagCount( r ).ShouldBe( tagsBefore + 1, "The version has been tagged." );
        File.Exists( r.WorkingFolderPath.AppendPart( _generated ) ).ShouldBeFalse( "The impacts are discarded." );
        using var e = r.CreateEditor();
        e.GitRepository.GetSimpleStatusInfo().IsDirty.ShouldBeFalse();
        e.GitRepository.Repository.Head.Tip.Tree[_generated].ShouldBeNull();
    }

    [Test]
    public async Task impacts_can_be_committed_Async()
    {
        using var testEnv = await TestHelper.CKliCreateFakeBuildTestEnvAsync().ConfigureAwait( false );
        var stack = await testEnv.CreateStackAsync( pluginConfigurationEditor: Helper.ConfigureFakeFeeds ).ConfigureAwait( false );
        var r = await CreateImpactedRepoAsync( stack.DefaultWorld ).ConfigureAwait( false );

        int commitsBefore;
        using( var e = r.CreateEditor() )
        {
            commitsBefore = e.GitRepository.Repository.Head.Commits.Count();
        }
        int tagsBefore = TagCount( r );
        using( TestHelper.Monitor.CollectTexts( out var logs ) )
        {
            (await CKliCommands.ExecAsync( TestHelper.Monitor, r.Root, "build", "--build-impacts", "commit" )).ShouldBeTrue();
            logs.ShouldContain( t => t.Contains( "they are amended to its commit (--build-impacts commit)" ) );
            logs.ShouldContain( t => t.StartsWith( "Building '" ) && t.EndsWith( "' again from the amended commit." ) );
        }
        TagCount( r ).ShouldBe( tagsBefore + 1, "The version has been tagged." );
        using( var e = r.CreateEditor() )
        {
            var git = e.GitRepository.Repository;
            e.GitRepository.GetSimpleStatusInfo().IsDirty.ShouldBeFalse();
            var head = git.Head.Tip;
            head.Message.ShouldContain( "Changes made by the build." );
            head.Tree[_generated].ShouldNotBeNull();
            head.Tree["Deleted.txt"].ShouldBeNull();
            // The built commit (the last one, not pushed) is amended: no commit is added for the impacts.
            git.Head.Commits.Count().ShouldBe( commitsBefore );
            head.Message.ShouldStartWith( "Touching 'Deleted.txt'." );
            // The version is tagged on the amended commit.
            git.Tags.Where( t => t.FriendlyName.Contains( "/v" ) || t.FriendlyName.StartsWith( 'v' ) )
                    .ShouldContain( t => t.PeeledTarget.Sha == head.Sha );
        }
        // Built again: nothing to build, nothing changes.
        (await CKliCommands.ExecAsync( TestHelper.Monitor, r.Root, "build" )).ShouldBeTrue();
        TagCount( r ).ShouldBe( tagsBefore + 1 );
    }

    [Test]
    public async Task impacts_fail_the_publish_Async()
    {
        using var testEnv = await TestHelper.CKliCreateFakeBuildTestEnvAsync().ConfigureAwait( false );
        var stack = await testEnv.CreateStackAsync( pluginConfigurationEditor: Helper.ConfigureFakeFeeds ).ConfigureAwait( false );
        var r = await CreateImpactedRepoAsync( stack.DefaultWorld ).ConfigureAwait( false );

        using( TestHelper.Monitor.CollectTexts( out var logs ) )
        {
            (await CKliCommands.ExecAsync( TestHelper.Monitor, r.Root, "publish", "--build-impacts", "discard" )).ShouldBeFalse();
            (await CKliCommands.ExecAsync( TestHelper.Monitor, r.Root, "publish" )).ShouldBeFalse();
            logs.ShouldContain( t => t.Contains( "files that a build creates, modifies or deletes must be committed or ignored" ) );
        }
    }

    [Test]
    public async Task invalid_build_impacts_value_Async()
    {
        using var testEnv = await TestHelper.CKliCreateFakeBuildTestEnvAsync().ConfigureAwait( false );
        var stack = await testEnv.CreateStackAsync( pluginConfigurationEditor: Helper.ConfigureFakeFeeds ).ConfigureAwait( false );
        var r = await stack.DefaultWorld.CreateRepoAsync( "X-Impacted", "v1.0.0" ).ConfigureAwait( false );
        using( TestHelper.Monitor.CollectTexts( out var logs ) )
        {
            (await CKliCommands.ExecAsync( TestHelper.Monitor, r.Root, "build", "--build-impacts", "keep" )).ShouldBeFalse();
            logs.ShouldContain( "Invalid '--build-impacts' value 'keep': it must be 'commit' or 'discard'." );
        }
    }

    static int TagCount( FakeBuildRepo repo )
    {
        using var e = repo.CreateEditor();
        return e.GitRepository.Repository.Tags.Count();
    }
}
